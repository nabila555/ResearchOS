"""Report builders: research summary, methodology analysis, research proposal.

Summary and methodology reports are assembled deterministically from verified paper
profiles (no extra model call). The proposal is drafted by the model from verified
profile statements and gap findings; every background sentence must cite papers that
exist, and everything the model proposes is labelled as a proposal.
"""

from datetime import datetime
from typing import Any

from app.ai.providers import ChatProvider
from app.citations import (
    CitationData,
    Style,
    bibliography,
    format_citation,
    in_text,
    replace_paper_labels,
)
from app.research_analysis.gaps import PaperDigest, digest_text
from app.research_analysis.profile import FIELDS

FIELD_LABELS = {f.key: f.label for f in FIELDS}
METHOD_FIELDS = ("methodology", "dataset", "sample_size", "population")


def _pages(evidence: dict[str, Any]) -> str:
    start, end = evidence.get("page_start"), evidence.get("page_end")
    if start is None:
        return ""
    return f"p. {start}" if end in (None, start) else f"pp. {start}–{end}"


def _statement(statement: dict[str, Any]) -> str:
    evidence = statement["evidence"]
    where = _pages(evidence)
    text = statement["text"].rstrip(".")
    mark = "" if evidence["verified"] else " ⚠ unverified"
    return f"{text}{f' ({where})' if where else ''}.{mark}"


def _field_block(fields: dict[str, Any], key: str) -> list[str]:
    value = fields.get(key) or {}
    statements = value.get("statements") or []
    if not statements:
        return ["_Not reported in the analysed text._"]
    if len(statements) == 1:
        return [_statement(statements[0])]
    return [f"- {_statement(s)}" for s in statements]


def _footer(model: str, generated_by_model: bool) -> list[str]:
    source = (
        f"drafted with {model}; sentences cite the papers they are based on"
        if generated_by_model
        else f"assembled from paper profiles extracted with {model}; no additional AI text"
    )
    return [
        "",
        "---",
        f"_Generated by ResearchOS on {datetime.now():%Y-%m-%d}, {source}. Statements marked ⚠ "
        "could not be verified against the source text. Check important points against the "
        "cited pages._",
    ]


def references(items: list[CitationData], style: Style) -> list[str]:
    if not items:
        return []
    lines = ["## References", ""]
    for index, (_, formatted) in enumerate(bibliography(items, style)):
        lines += [(f"[{index + 1}] " if style == "ieee" else "") + formatted.markdown, ""]
    return lines


def summary_markdown(
    title: str,
    papers: list[tuple[CitationData | None, str, dict[str, Any]]],
    model: str,
    style: Style = "apa",
) -> str:
    """papers: (citation data or None for notes, document title, profile fields)."""
    lines = [f"# {title}", ""]
    for index, (cite, doc_title, fields) in enumerate(papers):
        if len(papers) > 1:
            lines += [f"## {doc_title}", ""]
        if cite is not None:
            lines += [f"**Reference:** {format_citation(cite, style).markdown}", ""]
        for spec in FIELDS:
            heading = "###" if len(papers) > 1 else "##"
            lines += [f"{heading} {spec.label}", "", *_field_block(fields, spec.key), ""]
        if index < len(papers) - 1:
            lines.append("")
    return "\n".join(lines + _footer(model, False)) + "\n"


def methodology_markdown(
    title: str,
    papers: list[tuple[CitationData | None, str, dict[str, Any], dict[str, Any] | None]],
    model: str,
    style: Style = "apa",
) -> str:
    """papers: (citation, title, profile fields, latest detective result or None)."""
    lines = [f"# {title}", "", "## Study designs and samples", ""]
    header = "| Paper | " + " | ".join(FIELD_LABELS[k] for k in METHOD_FIELDS) + " |"
    lines += [header, "|---" * (len(METHOD_FIELDS) + 1) + "|"]
    for cite, doc_title, fields, _ in papers:
        label = in_text(cite, style).strip("()") if cite else doc_title
        cells = []
        for key in METHOD_FIELDS:
            statements = (fields.get(key) or {}).get("statements") or []
            cells.append("<br>".join(_statement(s) for s in statements) or "_Not reported_")
        lines.append(f"| {label} | " + " | ".join(c.replace("|", "\\|") for c in cells) + " |")

    lines += ["", "## Limitations reported by the authors", ""]
    for cite, doc_title, fields, _ in papers:
        label = in_text(cite, style).strip("()") if cite else doc_title
        lines += [f"**{label}**", "", *_field_block(fields, "limitations"), ""]

    reviewed = [(c, t, d) for c, t, _, d in papers if d]
    if reviewed:
        lines += ["## Reproducibility (from Paper Detective runs)", ""]
        items = [c["label"] for c in reviewed[0][2].get("checklist", [])]
        lines += ["| Paper | " + " | ".join(items) + " |", "|---" * (len(items) + 1) + "|"]
        status = {
            "reported": "Reported",
            "not_found": "Not found",
            "unclear": "Unclear",
            "unverified": "Unverified",
        }
        for cite, doc_title, detective in reviewed:
            label = in_text(cite, style).strip("()") if cite else doc_title
            row = [status.get(c["status"], c["status"]) for c in detective.get("checklist", [])]
            lines.append(f"| {label} | " + " | ".join(row) + " |")
        lines += ["", "_“Not found” means not found in the excerpts the Detective analysed._", ""]
    else:
        lines += [
            "_Run the Paper Detective on these papers to add a reproducibility overview._",
            "",
        ]

    lines += references([c for c, *_ in papers if c], style)
    return "\n".join(lines + _footer(model, False)) + "\n"


# --- Research proposal (model-drafted) -----------------------------------------------------

PROPOSAL_SYSTEM = """You draft a research proposal for a researcher, based on verified summaries \
of papers in their library (labelled P1, P2, ...) and, if given, research gaps found earlier.

Rules:
- "background" and "problem" sentences describe existing work: each must list the papers that \
support it in "papers". Do not invent findings, numbers or papers.
- Research questions, objectives, methods, contributions and risks are YOUR proposals: write \
them as proposals, concrete and feasible, building on the gaps.
- Keep each item to one or two sentences. Use a neutral academic register.
- Do not put citation markers like (P1) inside the text; list papers in "papers" instead."""

_CLAIM = {
    "type": "object",
    "properties": {
        "text": {"type": "string"},
        "papers": {"type": "array", "items": {"type": "integer"}},
    },
    "required": ["text", "papers"],
    "additionalProperties": False,
}
_LIST = {"type": "array", "items": {"type": "string"}}
PROPOSAL_SCHEMA: dict[str, Any] = {
    "type": "object",
    "properties": {
        "working_title": {"type": "string"},
        "background": {"type": "array", "items": _CLAIM},
        "problem": {"type": "array", "items": _CLAIM},
        "research_questions": _LIST,
        "objectives": _LIST,
        "methodology": _LIST,
        "expected_contributions": _LIST,
        "risks_and_limitations": _LIST,
    },
    "required": [
        "working_title",
        "background",
        "problem",
        "research_questions",
        "objectives",
        "methodology",
        "expected_contributions",
        "risks_and_limitations",
    ],
    "additionalProperties": False,
}


def proposal_prompt(
    digests: list[PaperDigest], topic: str | None, gaps: dict[str, Any] | None
) -> str:
    parts = []
    if topic:
        parts.append(f"Proposal topic / research interest: {topic}")
    parts.append("Papers:\n\n" + "\n\n".join(digest_text(d) for d in digests))
    if gaps:
        gap_lines = []
        for category in gaps.get("categories", []):
            for item in category.get("items", []):
                refs = ", ".join(p["label"] for p in item.get("papers", []))
                basis = "literature" if item.get("basis") == "literature" else "hypothesis"
                tag = f"{category['label']}; {basis}" + (f"; {refs}" if refs else "")
                gap_lines.append(f"- [{tag}] {item['statement']}")
        if gap_lines:
            parts.append("Research gaps identified earlier:\n" + "\n".join(gap_lines[:30]))
    return "\n\n".join(parts)


def verify_claims(raw: list[Any], valid_numbers: set[int], limit: int = 8) -> list[dict[str, Any]]:
    claims = []
    for item in raw[:limit]:
        text = str(item.get("text", "")).strip()[:800]
        if not text:
            continue
        refs = [n for n in dict.fromkeys(item.get("papers") or []) if isinstance(n, int)]
        valid = [n for n in refs if n in valid_numbers]
        claims.append({"text": text, "papers": valid, "supported": bool(valid)})
    return claims


def draft_proposal(
    provider: ChatProvider,
    digests: list[PaperDigest],
    topic: str | None,
    gaps: dict[str, Any] | None,
) -> dict[str, Any]:
    data = provider.generate_json(
        PROPOSAL_SYSTEM, proposal_prompt(digests, topic, gaps), PROPOSAL_SCHEMA, max_tokens=2200
    )
    numbers = set(range(1, len(digests) + 1))

    def strings(key: str, limit: int = 6) -> list[str]:
        return [str(s).strip()[:600] for s in (data.get(key) or [])[:limit] if str(s).strip()]

    return {
        "working_title": str(data.get("working_title") or "").strip()[:300],
        "background": verify_claims(data.get("background") or [], numbers),
        "problem": verify_claims(data.get("problem") or [], numbers, 5),
        "research_questions": strings("research_questions"),
        "objectives": strings("objectives"),
        "methodology": strings("methodology", 8),
        "expected_contributions": strings("expected_contributions"),
        "risks_and_limitations": strings("risks_and_limitations"),
        "papers": [
            {"label": d.label, "document_id": d.document_id, "title": d.title} for d in digests
        ],
        "topic": topic,
        "used_gap_analysis": gaps is not None,
    }


def proposal_markdown(
    title: str,
    result: dict[str, Any],
    cite_by_label: dict[str, CitationData | None],
    model: str,
    style: Style = "apa",
) -> str:
    numbers: dict[str, int] = {}

    def cite_sentence(claim: dict[str, Any]) -> str:
        def resolve(label: str) -> tuple[CitationData, int] | None:
            data = cite_by_label.get(label)
            if data is None:
                return None
            numbers.setdefault(label, len(numbers) + 1)
            return data, numbers[label]

        text, named = replace_paper_labels(claim["text"].rstrip("."), resolve, style)
        refs = []
        for n in claim["papers"]:
            label = f"P{n}"
            data = cite_by_label.get(label)
            if data is None or label in named:
                continue
            numbers.setdefault(label, len(numbers) + 1)
            refs.append(in_text(data, style, numbers[label]))
        if refs:
            text += (
                " " + ", ".join(refs)
                if style == "ieee"
                else " (" + "; ".join(r.strip("()") for r in refs) + ")"
            )
        return text + "." + ("" if claim["supported"] else " [⚠ unsupported]")

    heading = result["working_title"] or title
    lines = [
        f"# {heading}",
        "",
        "_Draft research proposal generated by AI from your library. Every "
        "section after “Problem statement” is a proposal to refine, not a finding._",
        "",
    ]
    if result.get("topic"):
        lines += [f"**Research interest:** {result['topic']}", ""]
    for key, label in (("background", "Background"), ("problem", "Problem statement")):
        lines += [f"## {label}", ""]
        claims = result[key]
        lines += [
            " ".join(cite_sentence(c) for c in claims)
            if claims
            else "_Not enough information in the sources._",
            "",
        ]
    for key, label, numbered in (
        ("research_questions", "Proposed research questions", True),
        ("objectives", "Objectives", False),
        ("methodology", "Proposed methodology", False),
        ("expected_contributions", "Expected contributions", False),
        ("risks_and_limitations", "Risks and limitations", False),
    ):
        items = result[key]
        if not items:
            continue
        lines += [f"## {label}", ""]
        lines += [f"{i + 1}. {item}" if numbered else f"- {item}" for i, item in enumerate(items)]
        lines.append("")
    # Only papers actually cited in the text go into the reference list (IEEE: in citation order).
    cited = [cite_by_label[label] for label in sorted(numbers, key=numbers.get)]
    lines += references([c for c in cited if c is not None], style)
    return "\n".join(lines + _footer(model, True)) + "\n"
