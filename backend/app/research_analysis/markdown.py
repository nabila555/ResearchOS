"""Render analysis results as Markdown reports (stored in `reports`, downloadable)."""

from datetime import datetime
from typing import Any

from app.research_analysis.detective import CATEGORIES as DETECTIVE_CATEGORIES
from app.research_analysis.profile import FIELDS


def _pages(evidence: dict[str, Any] | None) -> str:
    if not evidence or evidence.get("page_start") is None:
        return ""
    start, end = evidence["page_start"], evidence.get("page_end")
    return f"p. {start}" if end in (None, start) else f"pp. {start}–{end}"


def _statement(statement: dict[str, Any]) -> str:
    evidence = statement["evidence"]
    where = _pages(evidence)
    marker = "" if evidence["verified"] else " ⚠ unverified"
    return f"{statement['text']}{f' ({where})' if where else ''}{marker}"


def _cell(field: dict[str, Any] | None) -> str:
    if not field or field["status"] == "not_reported":
        return "_Not reported_"
    return "<br>".join(_statement(s) for s in field["statements"]).replace("|", "\\|")


def _footer(model: str) -> str:
    return (
        f"\n---\n_Generated by ResearchOS on {datetime.now():%Y-%m-%d} using {model}. "
        "Statements marked ⚠ could not be verified against the source text. "
        "AI output can be wrong: check important points against the cited pages._\n"
    )


def comparison_markdown(title: str, result: dict[str, Any], model: str) -> str:
    docs = result["documents"]
    header = "| Aspect | " + " | ".join(d["title"].replace("|", "\\|") for d in docs) + " |"
    divider = "|---|" + "---|" * len(docs)
    rows = [
        f"| **{spec.label}** | "
        + " | ".join(_cell(result["profiles"].get(str(d["id"]), {}).get(spec.key)) for d in docs)
        + " |"
        for spec in FIELDS
    ]
    return f"# {title}\n\n{header}\n{divider}\n" + "\n".join(rows) + "\n" + _footer(model)


def gaps_markdown(title: str, result: dict[str, Any], model: str) -> str:
    lines = [f"# {title}", ""]
    if result.get("focus"):
        lines += [f"Focus: {result['focus']}", ""]
    lines += ["## Papers analysed", ""]
    lines += [
        f"- **{p['label']}** {p['title']}" + (f" ({p['year']})" if p.get("year") else "")
        for p in result["papers"]
    ]
    for category in result["categories"]:
        lines += ["", f"## {category['label']}", ""]
        if not category["items"]:
            lines.append("_Nothing identified from these papers._")
        for item in category["items"]:
            if item["basis"] == "literature":
                tag = "Supported by literature: " + ", ".join(p["label"] for p in item["papers"])
            else:
                tag = "AI-generated hypothesis"
            lines.append(f"- **[{tag}]** {item['statement']}")
            if item["rationale"]:
                lines.append(f"  - {item['rationale']}")
            for note in item["notes"]:
                lines.append(f"  - ⚠ {note}")
    return "\n".join(lines) + "\n" + _footer(model)


def detective_markdown(title: str, result: dict[str, Any], model: str) -> str:
    lines = [
        f"# {title}",
        "",
        "_Analytical observations based on "
        f"{result.get('excerpts_analyzed', 0)} excerpts of the paper, not definitive judgements._",
        "",
        "## Observations",
        "",
    ]
    if not result["observations"]:
        lines.append("_No observations._")
    for obs in result["observations"]:
        label = DETECTIVE_CATEGORIES.get(obs["category"], obs["category"])
        lines.append(f"- **{label}** ({obs['severity']}): {obs['observation']}")
        if obs["kind"] == "absence":
            lines.append(
                "  - Based on absence in the analysed excerpts; the full paper may cover it."
            )
        elif obs["evidence"]:
            ev = obs["evidence"]
            lines.append(
                f"  - “{ev['quote']}” {_pages(ev)}"
                + ("" if ev["verified"] else " ⚠ quote not verified")
            )
    lines += ["", "## Reproducibility checklist", "", "| Item | Status |", "|---|---|"]
    status_text = {
        "reported": "Reported",
        "not_found": "Not found in excerpts",
        "unclear": "Unclear",
        "unverified": "Claimed, quote not verified",
    }
    for item in result["checklist"]:
        where = _pages(item["evidence"])
        lines.append(
            f"| {item['label']} | {status_text[item['status']]}{f' ({where})' if where else ''} |"
        )
    return "\n".join(lines) + "\n" + _footer(model)
